    c_sin = rng.normal(scale=1.0, size=(N + 1, M + 1))
    c_sin[:, 0] = 0.0  # the m=0 term has no sine component
    # -----------------------------
    # Build polar grid
    # -----------------------------
    # Coordinates centred at (0,0)
    x = np.linspace(-radius_px, radius_px, grid_size)
    y = np.linspace(-radius_px, radius_px, grid_size)
    X, Y = np.meshgrid(x, y)
    R = np.sqrt(X**2 + Y**2)
    Theta = np.arctan2(Y, X)  # angle in radians

    # Disk mask
    disk = R <= radius_px
    R_norm = R[disk] / radius_px  # normalised radius in [0,1] inside the disk

    # -----------------------------
    # Evaluate the Fourier series
    # -----------------------------
    F = np.zeros_like(R_norm)

    for n in range(N + 1):
        # radial basis: cos(pi n r)
        R_n = np.cos(np.pi * n * R_norm)
        for m in range(M + 1):
            cos_term = c_cos[n, m] * np.cos(m * Theta[disk])
            sin_term = c_sin[n, m] * np.sin(m * Theta[disk])
            F += R_n * (cos_term + sin_term)

    # -----------------------------
    # Soft binarisation via sigmoid
    # -----------------------------
    def sigmoid(z):
        return 1.0 / (1.0 + np.exp(-z))

    mask_soft = sigmoid(beta * F)
    # Threshold at 0.5 to get a binary pattern; keep it soft if you prefer
    mask_binary = (mask_soft < 0.5).astype(np.float32)

    # Build a full image
    image = np.zeros((grid_size, grid_size), dtype=np.float32)
    image[disk] = mask_binary  # values are 0 or 1 inside the disk

