def generate_pattern_torch(grid_size, M, N, beta, c_cos, c_sin):
    device = c_cos.device
    radius_px = grid_size // 2 - 4

    x = torch.linspace(-radius_px, radius_px, grid_size, device=device)
    y = torch.linspace(-radius_px, radius_px, grid_size, device=device)
    Y, X = torch.meshgrid(y, x, indexing='ij')
    R = torch.sqrt(X**2 + Y**2)
    Theta = torch.atan2(Y, X)
    R_norm = R / radius_px

    F = torch.zeros_like(R_norm)

    for n in range(N + 1):
        R_n = torch.cos(math.pi * n * R_norm)
        for m in range(M + 1):
            F += R_n * (
                c_cos[n, m] * torch.cos(m * Theta) +
                c_sin[n, m] * torch.sin(m * Theta)
            )

    mask_soft = torch.sigmoid(beta * F)
    disk = (R <= radius_px).float()
    image = mask_soft * disk  # fully differentiable
    return image

def rotate_tensor(image, angle_deg):
    angle_rad = -angle_deg * math.pi / 180
    theta = torch.tensor([
        [math.cos(angle_rad), -math.sin(angle_rad), 0.0],
        [math.sin(angle_rad),  math.cos(angle_rad), 0.0]
    ], dtype=torch.float32, device=image.device).unsqueeze(0)
    grid = F.affine_grid(theta, image.size(), align_corners=False)
    return F.grid_sample(image, grid, mode='bilinear', padding_mode='zeros', align_corners=False)

def compute_overlap_torch(image1, image2, angle_deg):
    if image1.ndim == 2:
        image1 = image1.unsqueeze(0).unsqueeze(0)
    if image2.ndim == 2:
        image2 = image2.unsqueeze(0).unsqueeze(0)
    rotated = rotate_tensor(image2, angle_deg)
    return (image1 * rotated).sum()

def area_sweep_torch(image1, image2, angles=torch.linspace(0, 360, 72)):
    return torch.stack([compute_overlap_torch(image1, image2, a.item()) for a in angles])


