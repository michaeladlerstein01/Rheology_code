def compute_overlap(image1, image2, angle_deg):
    """
    Rotate image2 by angle_deg around its center, then compute overlap of white pixels with image1.
    Both image1 and image2 must be square binary images (values 0 or 1).
    """
    # Ensure binary masks
    mask1 = (image1 > 0.5).astype(np.float32)
    mask2 = (image2 > 0.5).astype(np.float32)

    # Rotate mask2 around the center
    rotated_mask2 = rotate(mask2, angle=angle_deg, reshape=False, order=1)

    # Compute overlap of white pixels (where both masks are 1)
    overlap = mask1 * rotated_mask2
    overlap_area = np.sum(overlap)
    return overlap_area



def area_sweep(image1, image2 ):
    theta = np.linspace(0 , 360 , 361)
    rot_area = []
