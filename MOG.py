def to_plate(poly_or_list):
    """Return a single Polygon (outer − holes) from list or Polygon."""
    if isinstance(poly_or_list, Polygon):
        return poly_or_list
    # list case
    outer = max(poly_or_list, key=lambda p: p.area)
    holes = [p.exterior.coords[:] for p in poly_or_list if p is not outer]
    return Polygon(outer.exterior.coords, holes)



