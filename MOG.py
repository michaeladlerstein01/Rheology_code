png_path = Path("/Users/michael_adlerstein/Desktop/kings stuff /Rheology_code/plate_B_hat.png")

desired_circle_mm = 50.0          # the green circle *inside* the shape
# ---------------------------------------------------------------
# 1.  load  alpha channel → hard mask
# ---------------------------------------------------------------
img_rgba = Image.open(png_path).convert("RGBA")
rgba     = np.asarray(img_rgba)
alpha     = rgba[..., 3]                          # 0..255
mask_raw  = (alpha > 128).astype(np.uint8)        # 1 = Fourier lobes
disk_mask = np.ones_like(mask_raw, dtype=np.uint8)
r, c      = np.indices(mask_raw.shape)
center_r, center_c = (np.array(mask_raw.shape) - 1) / 2
radius_px = mask_raw.shape[0] // 2 - 4            # same as earlier
inside    = (r-center_r)**2 + (c-center_c)**2 <= radius_px**2
disk_mask[~inside] = 0                            # outside the circle

# -------- desired plate area = disk minus Fourier lobes -------------
mask = disk_mask - mask_raw       # 1 = solid plate, 0 = cut-outs
# ---------------------------------------------------------------
# 2.  find *all* contours, keep exterior & holes separately
#    coordinates come as (row, col) pixel floats
# ---------------------------------------------------------------
contours = measure.find_contours(mask, 0.5)
if not contours:
    raise RuntimeError("No contour found in PNG.")

# -----------------------------------------------------------------
# 3.  geometric centre & mm-per-pixel scale
#     • centre_px  = centroid of all opaque pixels
#     • scale_mm_per_px chosen so the final green circle has
#       radius = desired_circle_mm
# -----------------------------------------------------------------
rows, cols = np.nonzero(mask)                       # opaque pixels
centre_px = np.array([rows.mean(), cols.mean()])    # (row, col)

# pixel-radius of every contour vertex
all_pts  = np.vstack(contours)                      # (k, 2)  [row, col]
radii_px = np.hypot(all_pts[:, 1] - centre_px[1],
                    all_pts[:, 0] - centre_px[0])

# ---------------------------------------------------------------
#  choose scaling mode
# ---------------------------------------------------------------
use_inscribed = True       # True  → polygon INSIDE the circle
                           # False → circle  INSIDE the polygon

if use_inscribed:
    radius_px = radii_px.max()      # largest vertex → inscribed
else:
    radius_px = radii_px.min()      # smallest vertex → circumscribed

scale_mm_per_px = desired_circle_mm / radius_px    # final scale factor
# ---------------------------------------------------------------
# 4.  write DXF
# ---------------------------------------------------------------
doc = ezdxf.new(dxfversion="R2013")
msp = doc.modelspace()

# inner reference circle (green)
msp.add_circle((0, 0), desired_circle_mm,
               dxfattribs={"layer": "0", "color": 3})

# every contour → LWPOLYLINE
for cnt in contours:
    x_mm = (cnt[:, 1] - centre_px[1]) * scale_mm_per_px
    y_mm = -(cnt[:, 0] - centre_px[0]) * scale_mm_per_px  # invert Y
    msp.add_lwpolyline(list(zip(x_mm, y_mm)),
                       format="xy",
                       close=True,
                       dxfattribs={"layer": "0", "color": 5})

# save
dxf_path = png_path.with_suffix(".dxf")
doc.saveas(dxf_path)
print("DXF written →", dxf_path)



def plot_dxf(file_path):
    doc = ezdxf.readfile(file_path)
    msp = doc.modelspace()

    fig, ax = plt.subplots()
    ax.set_aspect("equal")
    ax.set_title(f"DXF view — {file_path}")

    for ent in msp:
        etype = ent.dxftype()

        if etype == "LINE":
            s, e = ent.dxf.start, ent.dxf.end
            ax.plot([s.x, e.x], [s.y, e.y], "k-")

        elif etype == "LWPOLYLINE":
            pts = np.array(ent.get_points("xy"))[:, :2]   # (n,2)
            if getattr(ent, "closed", False):
                pts = np.vstack([pts, pts[0]])           # close loop
            ax.plot(pts[:, 0], pts[:, 1], "b-")

        elif etype == "CIRCLE":
            c   = ent.dxf.center                # Vec3
            rad = ent.dxf.radius
            ax.add_patch(plt.Circle((c.x, c.y), rad,
                                    fill=False, color="g"))

        elif etype == "ARC":
            c   = ent.dxf.center
            r   = ent.dxf.radius
            a0, a1 = ent.dxf.start_angle, ent.dxf.end_angle
            ang = np.linspace(a0, a1, 180)
            x = c.x + r * np.cos(np.deg2rad(ang))
            y = c.y + r * np.sin(np.deg2rad(ang))
            ax.plot(x, y, "r--")

    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    ax.grid(True)
    plt.show()


